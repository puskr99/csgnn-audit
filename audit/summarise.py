"""Summarise audit/results/*.json into a Markdown table (mean ± sd over seeds)."""
import glob, json, os, numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
PAPER = {"BUPT": dict(auc=0.9698, gmean=0.8262, recall=0.8317),
         "Sichuan": dict(auc=0.9539, gmean=0.8864, recall=0.8878)}
ROWS = [("released", "Released scoring (true test labels)"),
        ("shuffled_mean", "Same, test labels shuffled (mean of permutations)"),
        ("test_labels_0", "Same, all test labels set to 0"),
        ("lf_none", "Label-free: cost layer dropped"),
        ("lf_pred_row", "Label-free: row of predicted class"),
        ("lf_expected", "Label-free: expected cost row")]


def ms(v):
    return f"{np.mean(v):.4f} ± {np.std(v, ddof=1):.4f}" if len(v) > 1 else f"{v[0]:.4f}"


runs = [json.load(open(f)) for f in sorted(glob.glob(os.path.join(HERE, "results", "*.json")))]
print("# Audit results (generated by `audit/summarise.py`)\n")
print("Test set of the released split (`gen_mask`, random_state=2, 20/20/60). Seeds are passed to the released "
      "`setup_seed`; the released entry point uses 42 only. Mean ± sample sd over seeds.\n")
for ds in ("BUPT", "Sichuan"):
    for ep in sorted({r["max_epoch"] for r in runs if r["dataset"] == ds}):
        rs = [r for r in runs if r["dataset"] == ds and r["max_epoch"] == ep and "label_free_selected" not in r]
        if not rs:
            continue
        seeds = [r["seed"] for r in rs]
        p = PAPER[ds]
        print(f"## {ds}, released config ({ep} epoch{'s' if ep > 1 else ''}), seeds {seeds}\n")
        print(f"Published (Hu et al., TCSS 2023): AUC {p['auc']:.4f}, G-Mean {p['gmean']:.4f}, Recall {p['recall']:.4f}\n")
        s42 = next((r for r in rs if r["seed"] == 42), None)
        print("| Scoring of the same trained model | AUC (seed 42) | G-Mean (seed 42) | AUC | G-Mean | Macro recall |")
        print("|---|---|---|---|---|---|")
        for key, name in ROWS:
            a = [r["final"][key]["auc"] for r in rs]
            g = [r["final"][key]["gmean"] for r in rs]
            rc = [r["final"][key]["recall"] for r in rs]
            a42 = f"{s42['final'][key]['auc']:.4f}" if s42 else "–"
            g42 = f"{s42['final'][key]['gmean']:.4f}" if s42 else "–"
            print(f"| {name} | {a42} | {g42} | {ms(a)} | {ms(g)} | {ms(rc)} |")
        mx = [r["final"]["max_abs_prob_change_under_shuffle"] for r in rs]
        rp = [r["final"]["random_predictor"]["auc"] for r in rs]
        rpl = [r["final"]["random_predictor_released_transform"]["auc"] for r in rs]
        print(f"\nLargest change of a single test probability when only test labels are shuffled: "
              f"{max(mx):.4f} (max over seeds; per seed {', '.join(f'{x:.3f}' for x in mx)}).  ")
        print(f"Uniformly random predictor: AUC {np.mean(rp):.4f}; after the released label-indexed transform: "
              f"{np.mean(rpl):.4f}.\n")
    sel = [r for r in runs if r["dataset"] == ds and "label_free_selected" in r]
    for r in sel:
        s = r["label_free_selected"]
        f = r["final"]
        print(f"## {ds}, {r['max_epoch']} epochs, seed {r['seed']}: label-free validation selection\n")
        print(f"- Released scoring after the last epoch: AUC {f['released']['auc']:.4f}, G-Mean {f['released']['gmean']:.4f}")
        print(f"- Label-free, epoch {s['epoch']} and variant `{s['variant']}` chosen on validation (G-Mean + AUC): "
              f"AUC {s['test']['auc']:.4f}, G-Mean {s['test']['gmean']:.4f}, macro recall {s['test']['recall']:.4f}\n")
